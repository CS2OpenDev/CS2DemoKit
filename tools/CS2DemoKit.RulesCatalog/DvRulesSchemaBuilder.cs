    /// <summary>Wraps a schema node with the standard RESERVED annotation (schema-present, loader-rejected).</summary>
    private static JsonObject Reserved(JsonObject node, string why)
    {
        node["markdownDescription"] = ReservedPrefix + why;
        node["deprecated"] = true;
        return node;
    }

