/// <summary>
///     Generates the shipped <c>rules/dv-rules.schema.json</c> — the
///     JSON schema for v2 <c>ruleset:</c> documents that the pilot modeline
///     (<c>$schema=./dv-rules.schema.json</c>) drives editor completion + validation from. Emits a
///     fresh document from the generated <see cref="CatalogRoot" />, so its view/facet vocabulary never
///     drifts from the engine. The drift gate (<c>CatalogDriftTests</c>) byte-compares a regen
///     against the committed file.
///     <para>
///         The schema carries <b>two explicit shape lists</b> (compiler-plan §9 / spec §7):
///     </para>
///     <list type="bullet">
///         <item>
///             <b>Live in v2.0</b> (schema-valid, loader-accepts): duration literals, role
///             members (<c>victim.*</c>/<c>killer.*</c>/<c>assister.*</c> in expressions),
///             <c>binding:</c> modes (catalog data), <c>off:</c>, <c>actor: any</c>, <c>for_each:</c>.
///         </item>
///         <item>
///             <b>Live in v2.0</b> (un-reserved later): <c>show: as: ticks|seconds|time</c>
///             column display formatting, the <c>"m:ss[.frac]"</c> duration slot scalar, the
///             <c>catalog_version</c>/<c>min_app_version</c> provenance fields, and map-valued
///             <c>define:</c> (a string-keyed lookup table read via <c>ref[key]</c>).
///         </item>
///         <item>
///             <b>Reserved — not yet implemented</b> (schema-present, loader-rejects): the extra
///             bucket <c>per:</c> axes. The team namespaces (<c>round.team.*</c> /
///             <c>round.enemies.*</c> / <c>round.alive.*</c>) and <c>net.*</c>
///             <c>match:</c>/<c>where:</c> payload matching are now <b>live</b>.
///             Bucket composite <c>key:</c>-as-list and named <c>reduce:</c> reducers, and
///             condition source lists (a <c>flag:</c>/<c>highlight:</c> <c>when:</c> authored as a
///             list of predicates = their AND-conjunction) are now <b>live</b>.
///     </list>
/// </summary>
public static class DvRulesSchemaBuilder
{
    private const string ReservedPrefix = "RESERVED - not yet implemented. ";

    /// <summary>Builds the <c>dv-rules.schema.json</c> text from the generated catalog.</summary>
    /// <param name="catalog">The freshly-built catalog (its <c>views</c> family drives the facet enums).</param>
    /// <returns>Deterministic, indented JSON with LF line endings and a trailing newline (drift-comparable).</returns>
    public static string Build(CatalogRoot catalog)
    {
        ArgumentNullException.ThrowIfNull(catalog);

        List<CatalogView> views = catalog.Views.OrderBy(v => v.Name, StringComparer.Ordinal).ToList();

        JsonObject root = new()
        {
            ["$schema"] = "https://json-schema.org/draft/2020-12/schema",
            ["$id"] = "dv-rules.schema.json",
            ["title"] = "CS2DemoKit Rulesets v2",
            ["description"] =
                "Schema for v2 ruleset: documents (docs/rules-v2/rules-v2-spec.md, docs/rules-v2/rules-v2-compiler-plan.md). "
                + "GENERATED by tools/CS2DemoKit.RulesCatalog from the catalog's views family - edit the "
                + "generator, not this file. Shapes marked 'RESERVED' are present for forward completion but "
                + "the loader rejects them as not-yet-implemented.",
            ["type"] = "object",
            ["required"] = new JsonArray
            {
                "ruleset"
            },
            ["additionalProperties"] = false,
            ["properties"] = TopLevelProperties(),
            ["$defs"] = Defs(catalog, views)
        };

        return root.ToJsonString(new JsonSerializerOptions
            {
                WriteIndented = true
            })
            .ReplaceLineEndings("\n") + "\n";
    }

