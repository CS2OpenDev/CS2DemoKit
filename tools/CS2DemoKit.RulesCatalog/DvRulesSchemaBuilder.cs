    private static JsonObject Defs(CatalogRoot catalog, List<CatalogView> views)
    {
        JsonObject defs = new()
        {
            ["expression"] = ExpressionDef(),
            ["triggerRef"] = TriggerRefDef(views),
            ["match"] = MatchUnionDef(views),
            ["trigger"] = TriggerDef(),
            ["offTrigger"] = OffTriggerDef(),
            ["param"] = ParamDef(),
            ["defineBody"] = DefineBodyDef(),
            ["stat"] = StatDef(views),
            ["highlight"] = HighlightDef(),
            ["show"] = ShowDef(),
            ["scoreboardEntry"] = ScoreboardEntryDef(),
            ["table"] = TableDef(),
            ["tableColumn"] = TableColumnDef()
        };

        // Per-view match facet enums (compiler-plan §9): one $def per view, referenced by the stat's
        // per-view if/then. Ordered by view name for deterministic output.
        foreach (CatalogView view in views)
        {
            defs[MatchDefName(view.Name)] = PerViewMatchDef(view);
        }

        return defs;
    }

