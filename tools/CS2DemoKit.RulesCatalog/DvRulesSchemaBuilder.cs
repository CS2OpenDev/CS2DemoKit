    private static JsonObject TriggerRefDef(List<CatalogView> views)
    {
        JsonArray examples = [];
        foreach (CatalogView v in views)
        {
            examples.Add(v.Name);
        }

        examples.Add("raw.player_death");
        examples.Add("net.CDemoFileHeader");

        return new JsonObject
        {
            ["type"] = "string",
            ["markdownDescription"] =
                "A trigger source: a curated view (kill, bomb_planted, ...), a same-document `define:` name, "
                + "`raw.<event>` (a wire event with no actor convention), or `net.<Message>` (a net-message "
                + "trigger - both bare triggers and their match:/where: payload matching are live; a "
                + "net trigger's payload fields read under `event.<Field>`, typed from the netMessages catalog).",
            ["examples"] = examples
        };
    }

    private static JsonObject MatchUnionDef(List<CatalogView> views)
    {
        // Union of every view's facets - the base match: shape (per-view precision is added by the
        // stat's per-view if/then). Each facet's markdownDescription names its type + the views that
        // expose it + per-source availability.
        SortedDictionary<string, (string Type, SortedSet<string> Views, string Availability)> facets =
            new(StringComparer.Ordinal);
        foreach (CatalogView view in views)
        {
            foreach (CatalogFacet facet in view.Facets)
            {
                if (!facets.TryGetValue(facet.Name, out (string Type, SortedSet<string> Views, string Availability) acc))
                {
                    acc = (facet.Type, new SortedSet<string>(StringComparer.Ordinal), view.Availability);
                    facets[facet.Name] = acc;
                }

                acc.Views.Add(view.Name);
            }
        }

        JsonObject properties = new();
        foreach ((string name, (string type, SortedSet<string> exposedBy, string availability)) in facets)
        {
            properties[name] = new JsonObject
            {
                ["markdownDescription"] =
                    $"Facet `{name}` (type `{type}`). Exposed by: {string.Join(", ", exposedBy)}. "
                    + $"Availability: {availability}. Value is a unary test (literal / `in list` / comparison / `[lo..hi]`)."
            };
        }

        properties["actor"] = new JsonObject
        {
            ["enum"] = new JsonArray
            {
                "any"
            },
            ["markdownDescription"] =
                "Suppresses the view's implicit per-player actor binding (compiler-plan decision 3). "
                + "`any` is the only value live in v2.0."
        };

        return new JsonObject
        {
            ["type"] = "object",
            ["additionalProperties"] = false,
            ["markdownDescription"] =
                "Structured facet bindings for the triggering view. The valid facet set depends on `on:` - "
                + "see the per-view constraints. On a `net.<Message>` trigger, `match:` is a field-facet "
                + "form over the message payload: each `{ Field: <test> }` lowers to an `event.<Field>` "
                + "where:-conjunct (payload-facet matching).",
            ["properties"] = properties
        };
    }

    private static JsonObject PerViewMatchDef(CatalogView view)
    {
        JsonObject properties = new();
        foreach (CatalogFacet facet in view.Facets.OrderBy(f => f.Name, StringComparer.Ordinal))
        {
            properties[facet.Name] = new JsonObject
            {
                ["markdownDescription"] = $"`{facet.Name}` (type `{facet.Type}`) on view `{view.Name}`."
            };
        }

        properties["actor"] = new JsonObject
        {
            ["enum"] = new JsonArray
            {
                "any"
            },
            ["markdownDescription"] = "Suppress the implicit actor binding (`any` only)."
        };

        List<string> availableOn = view.Profiles
            .Where(p => p.ConcreteEvents.Count > 0)
            .Select(p => p.Profile)
            .OrderBy(p => p, StringComparer.Ordinal)
            .ToList();

        return new JsonObject
        {
            ["type"] = "object",
            ["additionalProperties"] = false,
            ["markdownDescription"] =
                $"match: facets for view `{view.Name}` (event `{view.Event}`, binding `{view.Binding}`). "
                + $"Available on: {(availableOn.Count > 0 ? string.Join(", ", availableOn) : "no profiles")}.",
            ["properties"] = properties
        };
    }

