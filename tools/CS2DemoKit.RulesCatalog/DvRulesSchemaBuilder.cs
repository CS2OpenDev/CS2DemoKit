    /// <summary>
    ///     The <c>when:</c> slot on a <c>flag:</c> stat or a <c>highlight:</c> (condition source
    ///     lists): a single boolean expression, or a <b>list</b> of expressions whose meaning is the
    ///     AND-conjunction of its items — <c>[a, b]</c> ≡ <c>(a) and (b)</c>. The list form is pure
    ///     authoring sugar (identical resolved AST, identity hash, and lowering to the joined string);
    ///     a single-item list equals the bare expression.
    /// </summary>
    private static JsonObject WhenSlot() => new()
    {
        ["markdownDescription"] =
            "A boolean condition. Either a single expression, or a **list** of expressions read as their "
            + "AND-conjunction (`[a, b]` ≡ `(a) and (b)`) — a convenience for declaring each input on its "
            + "own line. A single-item list equals the bare expression.",
        ["oneOf"] = new JsonArray
        {
            new JsonObject
            {
                ["$ref"] = "#/$defs/expression"
            },
            new JsonObject
            {
                ["type"] = "array",
                ["minItems"] = 1,
                ["items"] = new JsonObject
                {
                    ["$ref"] = "#/$defs/expression"
                }
            }
        }
    };

